// ---------------------------------------------------------------------------
// T90-⑦：咪咕 mrc（真逐字）的解密与转换
// ---------------------------------------------------------------------------
//
// 钉的是这几条：
// - **解密**：hex 文本 ⇒ 每 16 个 hex 字符 = 1 个 **64 位**字 ⇒ TEA 变体解密
//   ⇒ 8 字节小端 ⇒ **UTF-16LE** 拼接；
// - ⚠️ **词时间是绝对毫秒**（实测：行头 `[2045,649]` 的首词标签是 `(2045,499)`
//   ⇒ 词起点 == 行首 ⇒ **不加行首**；且「下一词起点 − 当前词起点 == 当前词时长」
//   **553/553** 全中 ⇒ 词与词首尾相接）；
// - ⚠️ **标签在词之后**（实测「文本片段数 − 标签数」**恒为 1**、行首片段恒非空、
//   行尾片段恒为空）⇒ 词 i 的文本 = **第 i 段**（标签**之前**的那一段）；
// - **元信息行**（制作信息 / 标题行）被丢掉 —— ⚠️ 咪咕的制作信息是**合并成一行**的
//   （行头 `[0,0]` + 一堆 `(0,0)` 零时长词元组）⇒ 判定只能用**去掉词元组后的文本**；
// - ⚠️ **不能用酷我那套「零时长 ⇒ 翻译」判据**（咪咕的零时长行是**制作信息**）；
// - **纯空格的词元组必须保留**（渲染层会 trim 掉它，但行文本仍保留那个空格
//   ⇒ 丢了它英文歌词会显示成 `CountingStars`）；
// - **零时长词** → 并入前一个词；**空文本的词** → 不产出标签。
//
// ⚠️ **真实密文不入库**：咪咕的 TEA 密钥是**公开**的
//    ⇒ 真实密文入库 = 把歌词放进公开仓库。
//    ⇒ 这里用**自己合成**的明文 + **独立手写**的加密器
//    ⇒ 生产代码的解密写错时，**这些用例会红**。
//
// ⚠️ **加密器为什么可信**：它与**上游快照的解密器**（洛雪 `mg/utils/mrc.js`）
//    逐字节互逆（`release/verify/t90-07-migu-encryptor-check.mjs` 验过）
//    ⇒ 「加密器与解密器一起理解错」这种假绿**被排除**了。
//
// ---------------------------------------------------------------------------

import { describe, it, expect } from 'vitest'

import { decryptMiguMrc } from '../electron/lyricCodecs/migu'
import { miguToEnhancedLrc, miguToPlainLrc } from '../electron/lyricWordFormat'
import { looksLikeLrc } from '../electron/lyricProvider'
import { makeMiguPayload, padToBlock } from './helpers/miguCipher'

// ---------------------------------------------------------------------------
// 占位样本（**自己编的歌词**，不是任何真实歌曲）
// ---------------------------------------------------------------------------

/** 一份最小的 mrc 明文（**带行头** ⇒ 解密不会抛「没有行头」）。 */
const PLAIN = '[2000,2000]都(2000,500)是(2500,500)'

/** 一份「什么都有」的 mrc 明文（标题行 / 制作信息行 / 歌词行）。 */
const PLAIN_FULL = [
  '[ti:占位歌名]',
  '[ar:占位歌手]',
  '[0,0]作(0,0)词(0,0)：(0,0)占(0,0)位(0,0)人(0,0)',
  '[2000,2000]都(2000,500)是(2500,500)勇(3000,500)敢(3500,500)',
].join('\n')

// ---------------------------------------------------------------------------
// 解密
// ---------------------------------------------------------------------------

describe('T90-⑦ · 咪咕 mrc 解密', () => {
  it('✅ **往返**：自己加密的载荷 ⇒ 解回**逐字节相同**的明文', () => {
    const payload = makeMiguPayload(PLAIN)
    // ⚠️ 载荷是 **hex 文本**（不是二进制）。
    expect(payload).toMatch(/^[0-9a-f]+$/)
    expect(decryptMiguMrc(payload)).toBe(padToBlock(PLAIN))
  })

  it('✅ 往返（含标题行与制作信息行的完整样本）', () => {
    const payload = makeMiguPayload(PLAIN_FULL)
    expect(decryptMiguMrc(payload)).toBe(padToBlock(PLAIN_FULL))
  })

  it('⚠️ **空串 ⇒ 抛错**（如实报「源不可用」，不返回空歌词）', () => {
    expect(() => decryptMiguMrc('')).toThrow(/咪咕/)
  })

  it('⚠️ **不是字符串 ⇒ 抛错**', () => {
    expect(() => decryptMiguMrc(undefined as unknown as string)).toThrow(/咪咕/)
  })

  it('⚠️ **载荷太短 ⇒ 原样返回**（不足 32 个 hex 字符 ⇒ 不可能是密文）', () => {
    expect(decryptMiguMrc('abc')).toBe('abc')
  })

  it('⚠️ **不是 hex ⇒ 抛错**（格式变了 ⇒ 如实报错，别把乱码当歌词）', () => {
    expect(() => decryptMiguMrc('z'.repeat(64))).toThrow(/咪咕/)
  })

  it('⚠️ **解出来没有行头 ⇒ 抛错**（密钥或格式变了）', () => {
    const payload = makeMiguPayload('这里没有任何行头只是一段普通文字而已')
    expect(() => decryptMiguMrc(payload)).toThrow(/咪咕/)
  })
})

// ---------------------------------------------------------------------------
// mrc → 增强 LRC
// ---------------------------------------------------------------------------

describe('T90-⑦ · miguToEnhancedLrc', () => {
  it('✅ **词时间是绝对毫秒**（不加行首）+ **标签在词之后**（词文本 = 标签之前那一段）', () => {
    const plain = '[2000,2000]都(2000,500)是(2500,500)勇(3000,500)敢(3500,500)'
    const out = miguToEnhancedLrc(plain)
    // ⚠️ 行首 2000、首词 2000 ⇒ **同一个值** ⇒ 证明没有「加行首」。
    expect(out).toBe('[00:02.00]<00:02.00>都<00:02.50>是<00:03.00>勇<00:03.50>敢')
    expect(looksLikeLrc(out)).toBe(true)
  })

  it('⚠️ **元信息行（制作信息）被丢掉**（咪咕把它合并成一行：行头 `[0,0]` + 零时长词）', () => {
    const plain = [
      '[0,0]作(0,0)词(0,0)：(0,0)占(0,0)位(0,0)人(0,0)',
      '[2000,2000]都(2000,500)是(2500,500)',
    ].join('\n')
    const out = miguToEnhancedLrc(plain)
    expect(out).toBe('[00:02.00]<00:02.00>都<00:02.50>是')
    // ⚠️ **零时长 ≠ 翻译**（酷我那套判据在咪咕上是错的）⇒ 不能把这一行当翻译留下。
    expect(out).not.toContain('作词')
  })

  it('⚠️ **标题行被丢掉**（靠歌名提示认出来）', () => {
    const plain = [
      '[1000,500]占位歌名(1000,500) - (1500,500)占位歌手(1500,500)',
      '[2000,2000]都(2000,500)是(2500,500)',
    ].join('\n')
    const out = miguToEnhancedLrc(plain, { title: '占位歌名' })
    expect(out).toBe('[00:02.00]<00:02.00>都<00:02.50>是')
  })

  it('⚠️ **无行头的行（`[ti:]` / `[ar:]`）被丢掉**', () => {
    const plain = ['[ti:占位歌名]', '[ar:占位歌手]', '[2000,2000]都(2000,500)'].join('\n')
    const out = miguToEnhancedLrc(plain)
    expect(out).toBe('[00:02.00]<00:02.00>都')
  })

  it('⚠️ **零时长词并入前一个词**（不单独成词）', () => {
    const plain = '[2000,2000]都(2000,500)好(2500,0)'
    expect(miguToEnhancedLrc(plain)).toBe('[00:02.00]<00:02.00>都好')
  })

  it('⚠️ **空文本的词不产出标签**（没有文字的「词」不是词）', () => {
    const plain = '[2000,2000]都(2000,500)(2500,500)好(2500,500)'
    expect(miguToEnhancedLrc(plain)).toBe('[00:02.00]<00:02.00>都<00:02.50>好')
  })

  it('⚠️ **纯空格的词元组必须保留**（丢了它英文歌词会显示成 `CountingStars`）', () => {
    const plain = '[2000,2000]Counting(2000,500) (2500,100)Stars(2600,500)'
    const out = miguToEnhancedLrc(plain)
    expect(out).toBe('[00:02.00]<00:02.00>Counting<00:02.50> <00:02.60>Stars')
    // ⚠️ 行文本里那个**空格**必须还在。
    expect(out.replace(/<[^>]*>/g, '')).toContain('Counting Stars')
  })

  it('⚠️ **一行里没有有效词 ⇒ 跳过该行**', () => {
    const plain = ['[2000,2000]都(2000,500)', '[3000,500]'].join('\n')
    expect(miguToEnhancedLrc(plain)).toBe('[00:02.00]<00:02.00>都')
  })

  it('✅ 空串 / 非串 ⇒ **返回空串**（不抛异常）', () => {
    expect(miguToEnhancedLrc('')).toBe('')
    expect(miguToEnhancedLrc(undefined as unknown as string)).toBe('')
  })
})

// ---------------------------------------------------------------------------
// lrc / trc → 行级 LRC
// ---------------------------------------------------------------------------

describe('T90-⑦ · miguToPlainLrc', () => {
  it('✅ **丢掉无行头的行与元信息行**，其余原样输出', () => {
    const plain = [
      '[ti:占位歌名]',
      '[ar:占位歌手]',
      '[00:00.00]占位歌名 - 占位歌手',
      '[00:02.04]作词：占位人',
      '[00:03.00]第一行',
      '[00:05.00]第二行',
    ].join('\n')
    expect(miguToPlainLrc(plain, { title: '占位歌名' })).toBe('[00:03.00]第一行\n[00:05.00]第二行')
  })

  it('✅ 普通行级 LRC 原样输出（时间戳不动）', () => {
    const plain = '[00:03.00]第一行\n[00:05.00]第二行'
    expect(miguToPlainLrc(plain)).toBe(plain)
  })

  it('✅ 空串 / 非串 ⇒ **返回空串**', () => {
    expect(miguToPlainLrc('')).toBe('')
    expect(miguToPlainLrc(undefined as unknown as string)).toBe('')
  })
})
