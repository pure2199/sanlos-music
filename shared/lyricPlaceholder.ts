// ---------------------------------------------------------------------------
// T93：占位歌词的判定 —— 「这句话不是歌词，是一句占位提示」
// ---------------------------------------------------------------------------
//
// ⚠️ 本文件**不得出现副作用**，也不得 import Electron / Node 内置模块 / DOM 类型：
//    主进程（`electron/lyricProvider.ts`）与渲染进程（`src/player/lyricSource.ts`）
//    **共用**同一个判定 ⇒ 两层不会漂移。
//    —— 与 `shared/lyricProvider.ts` 同一套规矩（那边是同一份代码的两层共用）。
//
// ---------------------------------------------------------------------------
// 为什么需要它（**已证**）
// ---------------------------------------------------------------------------
//
// 某些外部源在「这首歌没有歌词」时会返回**一句占位文本**而不是空 ——
// 咪咕实测返回的是 `[00:00.00]此歌曲为纯音乐，请欣赏`（**21 字 / 1 行**）。
//
// 旧的命中判据只看「`ok` 且原文非空」⇒ **占位骗过了整条源链**：
// 链子立刻返回 ⇒ 渲染层拿到 `origin = 'external'` ⇒
// 「线上匹配不上 ⇒ 回落内嵌（→ NAS）」那条分支**根本没被触发**。
//
// 实测后果：用户问「线上搜不到歌词，为什么不读内嵌歌词？」——
// 而那首歌的**内嵌歌词有 265 行真对白**（`readEmbeddedLyric` 实测 12350 字符）。
//
// ⚠️ 这**不是**「线上优先」政策的问题（T70 用户拍板的那条不动）——
//    是**判据太松**：只挡「空」，没挡「占位」。
//
// ---------------------------------------------------------------------------
// 判据（**刻意保守**）
// ---------------------------------------------------------------------------
//
// ```
// 占位 ⇔ 去掉时间戳后的正文 **长度 ≤ 40** 且 **命中占位特征**
// ```
//
// ⚠️ **长度闸门**保证长歌词一律不判占位；
// ⚠️ **特征词**保证「只有 1 行的真歌词」不判占位
//    （T90-⑨ 已记录「冷门歌可能只有 1 行」是**既有行为** ⇒ 本轮**不挡「短」**）。
//
// ---------------------------------------------------------------------------

// ---------------------------------------------------------------------------
// 常量
// ---------------------------------------------------------------------------

/**
 * 占位正文的最大长度（**去掉时间戳之后**）。
 *
 * ⚠️ 实测样本：咪咕那句 `[00:00.00]此歌曲为纯音乐，请欣赏` ⇒ 去掉时间戳后 **21 字**。
 * ⚠️ 40 字 = 足够容纳各家常见的一句提示，又**远短于**任何真歌词（一行真歌词通常 8–20 字，
 *    但**一首歌的正文**动辄几百字 ⇒ 长度闸门挡的是「**整首歌**」而不是「一行」）。
 */
export const PLACEHOLDER_MAX_LENGTH = 40

/**
 * 占位特征词（**中文**）—— 命中任意一个即可。
 *
 * ⚠️ 覆盖各家常见措辞（简体 / 繁体各一套）。
 */
export const PLACEHOLDER_FEATURES_ZH: readonly string[] = [
  '纯音乐',
  '纯音樂',
  '纯音',
  '请欣赏',
  '請欣賞',
  '暂无歌词',
  '暫無歌詞',
  '无歌词',
  '無歌詞',
  '没有歌词',
]

/**
 * 占位特征词（**英文**）—— 命中任意一个即可（匹配时**统一转小写**）。
 */
export const PLACEHOLDER_FEATURES_EN: readonly string[] = [
  'instrumental',
  'music only',
  'no lyrics',
  'no lyric',
]

// ---------------------------------------------------------------------------
// 内部
// ---------------------------------------------------------------------------

/** 行级时间戳：`[mm:ss]` / `[mm:ss.xx]` / `[mm:ss.xxx]` / `[mm:ss:xx]`。 */
const LINE_TIMESTAMP = /\[\d{1,3}:\d{1,2}(?:[.:]\d{1,3})?\]/g

/** 逐字时间戳：`<mm:ss.xx>`（逐字歌词的行内标记）。 */
const WORD_TIMESTAMP = /<\d{1,3}:\d{1,2}(?:[.:]\d{1,3})?>/g

// ---------------------------------------------------------------------------
// 判定
// ---------------------------------------------------------------------------

/**
 * 判断一段歌词文本**是不是占位提示**。
 *
 * ⚠️ **空串算占位**（=「本来就没有」）⇒ 调用方可以直接用它当「不算命中」的判据，
 *    不必再单独判空。
 *
 * @param text 歌词原文（可以是 LRC、纯文本，或空串）。
 * @returns 是占位提示 ⇒ `true`；是真歌词 ⇒ `false`。
 */
export function isPlaceholderLyric(text: string): boolean {
  // ⚠️ 运行期兜底：万一传进来不是字符串 ⇒ 当「空」⇒ 当占位（宁可少用一句，
  //    也不要把一句占位当成命中）。
  const raw = typeof text === 'string' ? text : ''
  // ⚠️ **先去掉时间戳**（行级 + 逐字）⇒ 只拿「正文」比。
  const body = raw.replace(WORD_TIMESTAMP, '').replace(LINE_TIMESTAMP, '').trim()
  if (body === '') return true
  // ⚠️ **长度闸门**：长正文一律不是占位（哪怕里面有「纯音乐」三个字）。
  if (body.length > PLACEHOLDER_MAX_LENGTH) return false
  if (PLACEHOLDER_FEATURES_ZH.some((feature) => body.includes(feature))) return true
  const lower = body.toLowerCase()
  return PLACEHOLDER_FEATURES_EN.some((feature) => lower.includes(feature))
}
