// ---------------------------------------------------------------------------
// 逐字时间戳判定（T108）—— 跨进程纯函数
// ---------------------------------------------------------------------------
//
// ⚠️ 本文件**不得出现副作用**，也不得 import Electron / Node 内置模块 / DOM 类型
//    （与 `shared/lyricProvider.ts` 同一套纪律：主进程与渲染层共用）。
//
// **为什么单独放一个文件**：
// - 主进程要判断「这份歌词**带不带逐字**」才能在**多个源**之间挑（T108 的核心）；
// - 而「逐字长什么样」的定义**只有一处**：渲染层 `src/ui/lyrics/parse.ts` 的
//   `WORD_TAG`（`<mm:ss.xx>` 词级标签）。
// - 两处各写一份正则 ⇒ 迟早漂移（一边改了格式，另一边还在按老格式挑源）
//   ⇒ 这里落一份**公理**，并由 `test/lyric-word-timed.test.ts` 断言它与渲染层的
//   `parseLyricEntries` 解析结果**一致** ⇒ 漂移会被测试当场抓住。
//
// ---------------------------------------------------------------------------

/**
 * 逐字标签：`<mm:ss.xx>`（A2 增强 LRC 格式）。
 *
 * ⚠️ **与渲染层 `src/ui/lyrics/parse.ts` 的 `WORD_TAG` 同口径**：
 *    - 形如 `<mm:ss>` / `<mm:ss.xx>` / `<mm:ss.xxx>` / `<mm:ss:xx>` 都认；
 *    - 小数位按**位数**折算（`N` 位 → ÷10^N）⇒ `.xx`=÷100、`.xxx`=÷1000；
 *    - 分钟可以超过 59（长音频）。
 *
 * ⚠️ **这里刻意不带 `g` 标志**：带 `g` 的正则对象带 `lastIndex` 状态，
 *    `test` / `exec` 复用同一个对象时**第二次可能漏匹配**
 *    （渲染层 `parseWordSegments` 因此每次都先 `WORD_TAG.lastIndex = 0`）。
 *    本文件只用 `test` ⇒ **不带 `g` 就天然没有这个坑**。
 */
const WORD_TAG = /<(\d+):(\d{1,2})(?:[.:](\d{1,9}))?>/

/**
 * 这份歌词原文**带不带逐字时间戳**。
 *
 * ⚠️ **判定是「整份文件」级**（不是逐行）：
 *    真实文件里逐字标签**可能只覆盖部分行**（外部源的增强 LRC 常见形态），
 *    所以「这份文件带逐字」≠「每一行都带逐字」。
 *    ⇒ 本函数**只用来在多个源之间挑哪一份**（T108），
 *    **不替代**渲染层**逐行**的 `wordTimed` 判定
 *    （`src/ui/lyrics/parse.ts` 的 `assemble`）。
 *
 * @param raw LRC 原文。
 * @returns 带逐字时间戳返回 `true`；否则 `false`。
 */
export function hasWordTimedTags(raw: string): boolean {
  if (typeof raw !== 'string' || raw === '') return false
  return WORD_TAG.test(raw)
}
