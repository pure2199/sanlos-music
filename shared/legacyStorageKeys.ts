// T115：里层命名全量改名 —— **旧 `localStorage` 键**（回落用，**一个字都不能改**）
// ---------------------------------------------------------------------------
//
// ⚠️ **为什么要有这个文件**：T115 把**四个** `localStorage` 键改了名，而这些键里存的是
//    **用户自己的数据**（本机播放记录 / 上次播到第几秒 / 按歌指定歌词源 / 有声读物的扫描结果）
//    ⇒ 直接改名 = **静默丢数据**（**还不报错**，最难排查的那一种）。
//
// ⇒ 办法：**新键没有**时**回落读旧键**（旧键**只读**、**不删**）
//    ⇒ 之后第一次写入自然落到新键 ⇒ **一次性迁移、幂等、零删除**。
//
// ⚠️ **「清空」必须两个键都删**：只删新键的话，新键一消失，下次读就**回落到旧键**
//    ⇒ 用户点了「清空」，记录却**复活**了 ⇒ 详见 `src/player/resumeBridge.ts`。
//    ⚠️ **但只有 `resume` 有「清空」入口** ⇒ 只有它需要「两个键都删」。
//    **有声那个 store 没有清空入口** ⇒ 不需要删旧键（撤销改判只改新键 ⇒ 旧键不会被读回）。
//
// ⚠️ **这些字面量一个字都不能改**：它们就是数据在磁盘上的原样。
//    ⇒ 改名脚本（`release/verify/t115-03-apply-rename.mjs`）**跳过本文件**。
// ---------------------------------------------------------------------------

