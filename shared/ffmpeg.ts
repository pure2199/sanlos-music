// ---------------------------------------------------------------------------
// FFmpeg 兜底解码的**共享类型**（Task 12）
// ---------------------------------------------------------------------------
//
// ⚠️ **为什么放在 `shared/`**：渲染进程要读「FFmpeg 状态」与「兜底结果」，
//    主进程要产出同样的东西 → 放一份形状，两边共用。
//
// ---------------------------------------------------------------------------
// 边界
// ---------------------------------------------------------------------------
// - **不引新 npm 依赖**：只认**系统里已装**的 `ffmpeg` 可执行文件；
// - 渲染进程**永远不碰文件路径**：它只说「给 songId 兜底一下」；
// - 失败原因用**可判别的码**（`reason`）而不是靠中文文案匹配；
// - 所有文案**不含** token / Cookie / authx。

/** FFmpeg 探测结果。 */
export interface FfmpegStatus {
  /** 是否找到可用的 FFmpeg。 */
  available: boolean
  /** 可执行文件路径（找不到时是空串）。 */
  path: string
  /** 版本信息（通常是 `ffmpeg version …` 那一行；找不到时是空串）。 */
  version: string
}

/** 兜底失败的原因（**可判别**，不要靠文案匹配）。 */
export type FfmpegFallbackFailure =
  /** 本机没有 FFmpeg。 */
  | 'no-ffmpeg'
  /** 这首歌没有本地副本（兜底只支持本地文件）。 */
  | 'no-local'
  /** 转码失败（`detail` 里有原因）。 */
  | 'failed'

/** 兜底转码的结果。 */
export interface FfmpegFallbackResult {
  /**
   * 转码产物的可播放地址（`fnml://local/track/<id>`）。
   *
   * ⚠️ 成功时是**本地**地址（不经过 NAS、不带任何凭证）。
   */
  url: string
  /** 失败原因（可判别的码）；成功时是 `null`。 */
  reason: FfmpegFallbackFailure | null
  /** 失败细节（可读文案，**不含凭证**）；成功时是 `null`。 */
  detail: string | null
}
