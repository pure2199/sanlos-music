// ---------------------------------------------------------------------------
// 虚拟列表的**可视区高度**钳位（T22）
//
// ---------------------------------------------------------------------------
// 为什么需要这一层兜底
// ---------------------------------------------------------------------------
// 真实曲库的专辑有 34,071 张。真机上曾出现「一次性挂载 1,050 张卡片」的况：
//
//   1. flex item 的**自动最小尺寸**默认是 `min-height: auto` = 内容的 min-content 高度；
//   2. 主区 `.app-shell__main` 里装着虚拟网格，而网格**画布的高度 = 行数 × 行高**
//      （条目越多越高）→ 主区的自动最小尺寸跟着暴涨到 4 万多像素；
//   3. 主区被顶高 → 网格**没有负余量可压缩** → 网格量到的「可视区高度」
//      = **全部内容的高度**（真机实测 41,216px）；
//   4. 于是「可视区」= 全部内容 → **虚拟裁剪等于没裁剪** → 1,050 个节点
//      → 1,050 个封面请求把中继打到 502；
//   5. 同时，「内容填不满可视区就自动续一页」的副作用**永远成立**
//      （`contentHeight ≤ viewportHeight + rowHeight`）→ **无限翻页**。
//
// CSS 侧已经修掉了根因（主区 `min-height: 0`），但**这里再钳一道**：
// 万一布局又被别的东西顶开（将来新增的页面外壳 / 换主题 / 换字体），
// 挂载量与翻页次数也**不会失控**——因为可视区高度最多就是「一个窗口」。
//
// ---------------------------------------------------------------------------
// 钳位对象：**只有「量到的值」**
// ---------------------------------------------------------------------------
// ⚠️ 调用方**注入**的 `viewportHeight` 是显式契约（单测用它钉住裁剪边界，
//    允许比窗口还高）→ **一律不钳**。
//    钳了它，既有单测（`viewportHeight={224 * 10}`）会直接变红。
//
// ---------------------------------------------------------------------------

/**
 * 把量到的可视区高度钳到**窗口高度**。
 *
 * @param height 量到的可视区高度（像素）。
 * @returns 不超过窗口高度的高度（窗口尺寸不可用时原样返回）。
 */
export function clampViewportHeight(height: number): number {
  if (!Number.isFinite(height) || height <= 0) return height
  if (typeof window === 'undefined') return height
  const windowHeight = window.innerHeight
  // ⚠️ 窗口尺寸不可用（SSR / 非浏览器环境）→ 不钳。
  if (!Number.isFinite(windowHeight) || windowHeight <= 0) return height
  return Math.min(height, windowHeight)
}
